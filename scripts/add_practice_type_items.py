def main() -> None:
    existing = get(f"questions?program=eq.{PROGRAM}&year=eq.{YEAR}&select=round,number,question&order=round,number")
    by_round_sentences = {}
    next_num = {}
    for r in existing:
        rnd = r["round"]
        next_num[rnd] = max(next_num.get(rnd, 0), r["number"])
        # 예문(마지막 줄)으로 중복 판별
        by_round_sentences.setdefault(rnd, set()).add(r["question"].split("\n")[-1].strip())

    rows = []
    for rnd, q, sentence, answer, expl in NEW_ITEMS:
        if sentence.strip() in by_round_sentences.get(rnd, set()):
            continue  # 이미 있음
        next_num[rnd] = next_num.get(rnd, 0) + 1
        rows.append({
            "program": PROGRAM, "year": YEAR, "round": rnd, "number": next_num[rnd],
            "type": "essay", "points": 10, "passage": None,
            "question": f"{q}\n\n{sentence}", "options": None,
            "correct_answer": answer, "explanation": expl,
        })

    if not rows:
        print("추가할 새 항목 없음(이미 반영됨)")
        return
    post("questions", rows)
    after = get(f"questions?program=eq.{PROGRAM}&year=eq.{YEAR}&select=round&order=round")
    from collections import Counter
    c = Counter(r["round"] for r in after)
    print(f"{len(rows)}개 추가 · 유형별 현황 {dict(sorted(c.items()))}")


if __name__ == "__main__":
    main()
