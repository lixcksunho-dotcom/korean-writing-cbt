def main() -> None:
    for (program, year, rnd, num), changes in REWRITES.items():
        rows = get(
            f"questions?program=eq.{program}&year=eq.{year}&round=eq.{rnd}&number=eq.{num}"
            "&select=id,options,correct_answer"
        )
        if not rows:
            print(f"없음: {program} {year}-{rnd} #{num}")
            continue
        q = rows[0]
        opts = list(q["options"])
        ans = int(q["correct_answer"]) - 1
        assert ans not in changes, f"정답 선택지는 손대지 않는다: {program} {year}-{rnd} #{num}"
        for i, text in changes.items():
            opts[i] = text
        patch(f"questions?id=eq.{q['id']}", {"options": opts})
        lens = [len(o) for o in opts]
        print(f"{program} {year}-{rnd} #{num} 길이 {lens} (정답 {ans + 1})")


if __name__ == "__main__":
    main()
