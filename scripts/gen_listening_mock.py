def env():
    e = {}
    for line in (ROOT / ".env.local").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            e[k.strip()] = v.strip().strip('"').strip("'")
    return e


def main():
    e = env()
    base = e["NEXT_PUBLIC_SUPABASE_URL"].rstrip("/")
    key = e["SUPABASE_SERVICE_ROLE_KEY"]
    tmp = Path(tempfile.gettempdir())
    urls = {}
    for n, text in SCRIPTS.items():
        mp3 = tmp / f"kbs_mock_listen_{n}.mp3"
        subprocess.run([sys.executable, "-m", "edge_tts", "--voice", VOICE,
                        "--text", text, "--write-media", str(mp3)], check=True)
        path = f"listening/{PROGRAM}-{YEAR}-{ROUND}-{n}.mp3"
        req = urllib.request.Request(f"{base}/storage/v1/object/{BUCKET}/{path}",
            method="POST", data=mp3.read_bytes(),
            headers={"Authorization": "Bearer " + key, "apikey": key,
                     "Content-Type": "audio/mpeg", "x-upsert": "true"})
        urllib.request.urlopen(req, timeout=60)
        urls[n] = f"{base}/storage/v1/object/public/{BUCKET}/{path}"
        print(f"[{n}] ok")
    print("URLS=" + json.dumps(urls, ensure_ascii=False))


if __name__ == "__main__":
    main()
