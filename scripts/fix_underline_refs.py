# A: 발문이 따옴표로 대상을 밝히는 형태
TARGET_RE = re.compile(r"밑줄 [친그]은? ?[^'\n]*'([^']+)'")


def underline_target(question: str) -> str | None:
    """발문의 대상을 예문에서 찾아 __…__로 감싼 새 question. 못 찾으면 None."""
    head, _, body = question.partition("\n")
    if not body.strip():
        return None
    m = TARGET_RE.search(head)
    if not m:
        return None
    target = re.sub(r"\([^)]*\)", "", m.group(1)).strip()  # '괴리(乖離)' → '괴리'
    if target in body:
        return head + "\n" + body.replace(target, f"__{target}__", 1)

    # 활용형 대응: 원형의 '다'를 떼고 찾되, 어절 끝까지 밑줄을 늘려 '먹고'를 '__먹__고'로 자르지 않는다.
    if target.endswith("다"):
        stem = target[:-1]
        i = body.find(stem)
        if i >= 0:
            j = i + len(stem)
            while j < len(body) and not body[j].isspace() and body[j] not in ".,!?'\"”’」":
                j += 1
            return head + "\n" + body[:i] + f"__{body[i:j]}__" + body[j:]
    return None


def main() -> None:
    dry = "--dry" in sys.argv
    rows = get("questions?select=id,program,year,round,number,question&type=eq.multiple&order=program,year,round,number")
    log, changed = [], 0
    for r in rows:
        q = r["question"]
        if "밑줄" not in q or "__" in q:
            continue
        head = q.split("\n")[0]
        new = q.replace(head, STEM_REWRITES[head], 1) if head in STEM_REWRITES else q
        # 발문을 고치면서 대상이 따옴표로 드러난 문항은 예문에도 밑줄을 넣는다.
        new = underline_target(new) or new
        if new == q:
            continue
        log.append(f"[{r['program']} {r['year']}-{r['round']} #{r['number']}]\n- {q[:160]}\n+ {new[:160]}\n")
        changed += 1
        if not dry:
            patch(f"questions?id=eq.{r['id']}", {"question": new})

    out = HERE.parent / "scripts" / "_underline_changes.txt"
    out.write_text("\n".join(log), encoding="utf-8")
    print(f"{'(dry) ' if dry else ''}{changed}문항 변경 · 내역 {out}")


if __name__ == "__main__":
    main()
